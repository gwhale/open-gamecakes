// Maze With Gates — config types, helpers, and the kid-designed Crayon Maze.
//
// A different mechanic from Math Maze:
//   - Math Maze: you tap cells that satisfy a rule; the math IS the movement.
//   - Maze With Gates: you walk freely through a maze; the math is a BARRIER
//     at specific "gate" cells. Reach a gate → a challenge modal opens →
//     answer correctly → the gate unlocks and you can pass through it.
//
// This file is pure TypeScript — no React, no DOM, no Supabase. The config
// type is designed to be JSON-serializable so the future game-creator
// pipeline (spec §7) can emit one from a kid's drawing and parent approval,
// and this same renderer will play it.
//
// Source: inspired by a founding kid's hand-drawn maze (2026-04-11).
// She drew a freeform orange-marker maze with ~9 math gates and instructions
// "Answer correctly, you might go in that direction." This config is a
// grid-quantized interpretation of that drawing, not a pixel reproduction.
// Her specific math problems are preserved in their approximate order.

import { generateMathChallenge, type MathType } from '@/lib/games/shared/generate-challenge';
import { isConceptType } from '@/lib/games/shared/generate-concept-challenge';
import type { MathKind } from '@/lib/games/shared/challenge-mode';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface MazeGatesPosition {
  row: number;
  col: number;
}

/** Cell types. Each grid cell is exactly one of these.
 *  `start` and `end` are walkable (the character stands on them); they're
 *  distinct from `path` only so we can render markers and pick them up
 *  without a separate coordinate lookup. */
export type Cell = 'wall' | 'path' | 'gate' | 'start' | 'end';

/** A challenge the kid must answer to unlock a gate.
 *  Tagged union so different challenge types can be added without breaking
 *  existing configs. `numeric` carries a pre-rendered prompt + answer so it can
 *  hold any operation generated by generateMathChallenge (add/sub/mult/mixed). */
export type Challenge =
  | { type: 'addition'; a: number; b: number }
  | { type: 'numeric'; prompt: string; answer: number };

export function challengeAnswer(c: Challenge): number {
  switch (c.type) {
    case 'addition':
      return c.a + c.b;
    case 'numeric':
      return c.answer;
  }
}

/** Human-readable prompt for the challenge modal. */
export function challengePrompt(c: Challenge): string {
  switch (c.type) {
    case 'addition':
      return `${c.a} + ${c.b}`;
    case 'numeric':
      return c.prompt;
  }
}

export interface GateDef {
  id: string;
  position: MazeGatesPosition;
  challenge: Challenge;
}

/** Theme controls the visual feel. Hand-drawn aesthetic is the whole point
 *  of this template — expose the colors as config so the same renderer
 *  can theme different mazes differently (per kid-designed maze, or custom). */
export interface MazeGatesTheme {
  playerGlyph: string;           // emoji for the player character
  wallColor: string;             // CSS color for rough-drawn wall strokes
  gateColor: string;             // unsolved gate fill/stroke
  gateSolvedColor: string;       // solved gate fill/stroke
  pathColor: string;             // subtle path hint
  backgroundColor: string;       // "paper" color
  accentColor: string;           // start/end markers, highlights
}

export interface MazeGatesConfig {
  version: 1;
  title: string;
  /** Who designed this game. Rendered in the UI header as a "by the designer kid"
   *  byline so the kid sees their name on their own game. */
  designer?: string;
  theme: MazeGatesTheme;
  grid: {
    rows: number;
    cols: number;
    cells: Cell[][]; // cells[row][col]
  };
  start: MazeGatesPosition;
  end: MazeGatesPosition;
  gates: GateDef[];
}

// ---------------------------------------------------------------------------
// Pure helpers (renderer + logic)
// ---------------------------------------------------------------------------

export function positionsEqual(a: MazeGatesPosition, b: MazeGatesPosition): boolean {
  return a.row === b.row && a.col === b.col;
}

export function isAdjacent(a: MazeGatesPosition, b: MazeGatesPosition): boolean {
  const dr = Math.abs(a.row - b.row);
  const dc = Math.abs(a.col - b.col);
  return (dr === 1 && dc === 0) || (dr === 0 && dc === 1);
}

export function cellAt(
  config: MazeGatesConfig,
  pos: MazeGatesPosition,
): Cell | undefined {
  const { rows, cols, cells } = config.grid;
  if (pos.row < 0 || pos.row >= rows) return undefined;
  if (pos.col < 0 || pos.col >= cols) return undefined;
  return cells[pos.row]?.[pos.col];
}

export function gateAt(
  config: MazeGatesConfig,
  pos: MazeGatesPosition,
): GateDef | undefined {
  return config.gates.find((g) => positionsEqual(g.position, pos));
}

/**
 * Can the character step INTO this cell? Walls are never passable. Path /
 * start / end are always passable. A gate is passable only once its
 * challenge has been solved — otherwise stepping into it triggers the
 * challenge modal but does NOT actually move the character.
 */
export function isPassable(
  config: MazeGatesConfig,
  pos: MazeGatesPosition,
  solvedGates: ReadonlySet<string>,
): boolean {
  const cell = cellAt(config, pos);
  if (cell === undefined || cell === 'wall') return false;
  if (cell === 'gate') {
    const gate = gateAt(config, pos);
    return gate ? solvedGates.has(gate.id) : false;
  }
  return true; // path | start | end
}

// ---------------------------------------------------------------------------
// Session summary (for the /api/attempts POST body)
// ---------------------------------------------------------------------------

export interface MazeGatesSessionSummary {
  taps_total: number;
  taps_wrong: number;
  optimal_taps: number;
  efficiency: number;
  completed: boolean;
  session_ms: number;
}

/**
 * Derive a session summary for the adaptive engine.
 *
 * "Efficiency" here is `gates_solved / (gates_solved + wrong_answers)`.
 * A perfect run (answered every gate right on the first try) scores 1.0.
 * A sloppy run (wrong answers along the way) scores lower.
 *
 * Movement taps (walking through already-open corridor) are NOT counted —
 * they aren't educational, only the challenge answers are. This matches
 * how Math Maze defines efficiency for its mechanic and keeps the server
 * side mastery function agnostic to which template produced the score.
 */
export function summarizeMazeSession(args: {
  gatesTotal: number;
  gatesSolved: number;
  wrongAnswers: number;
  completed: boolean;
  sessionMs: number;
}): MazeGatesSessionSummary {
  const optimal = args.gatesTotal;
  const total = args.gatesSolved + args.wrongAnswers;
  const efficiency = total > 0 ? args.gatesSolved / total : 0;
  return {
    taps_total: total,
    taps_wrong: args.wrongAnswers,
    optimal_taps: optimal,
    efficiency,
    completed: args.completed,
    session_ms: args.sessionMs,
  };
}

// ---------------------------------------------------------------------------
// Grid builder — construct a MazeGatesConfig from a path array
// ---------------------------------------------------------------------------
//
// Rather than hand-drawing an ASCII grid (error-prone, hard to reason
// about connectivity), we describe the maze by listing the SEQUENCE of
// cells along the main path from start to end. Everything off the path
// becomes a wall. Gate positions are specified by index into that path.
// This guarantees connectivity by construction and makes the design
// readable — the TypeScript literal describes the path you actually walk.

interface PathGateSpec {
  /** Zero-based index into the path array. Index 0 is start, last is end.
   *  Don't place gates at index 0 or at the last index. */
  pathIndex: number;
  challenge: Challenge;
}

function buildConfigFromPath(args: {
  rows: number;
  cols: number;
  path: readonly (readonly [number, number])[];
  gates: readonly PathGateSpec[];
  title: string;
  designer?: string;
  theme: MazeGatesTheme;
}): MazeGatesConfig {
  const { rows, cols, path, gates, title, designer, theme } = args;

  // Validate path
  if (path.length < 2) throw new Error('path must have at least 2 cells');
  for (const [r, c] of path) {
    if (r < 0 || r >= rows || c < 0 || c >= cols) {
      throw new Error(`path cell out of bounds: (${r},${c})`);
    }
  }
  // Validate adjacency
  for (let i = 1; i < path.length; i++) {
    const [r1, c1] = path[i - 1];
    const [r2, c2] = path[i];
    const dr = Math.abs(r1 - r2);
    const dc = Math.abs(c1 - c2);
    if (!((dr === 1 && dc === 0) || (dr === 0 && dc === 1))) {
      throw new Error(`path cells ${i - 1} and ${i} are not orthogonally adjacent: (${r1},${c1}) → (${r2},${c2})`);
    }
  }

  // Start with all walls
  const cells: Cell[][] = Array.from({ length: rows }, () =>
    Array.from({ length: cols }, () => 'wall' as Cell),
  );

  // Paint the path
  for (const [r, c] of path) {
    cells[r][c] = 'path';
  }

  // Mark gates
  const gateDefs: GateDef[] = [];
  for (let i = 0; i < gates.length; i++) {
    const spec = gates[i];
    if (spec.pathIndex <= 0 || spec.pathIndex >= path.length - 1) {
      throw new Error(`gate ${i} pathIndex ${spec.pathIndex} must be between 1 and ${path.length - 2}`);
    }
    const [r, c] = path[spec.pathIndex];
    cells[r][c] = 'gate';
    gateDefs.push({
      id: `g${i + 1}`,
      position: { row: r, col: c },
      challenge: spec.challenge,
    });
  }

  // Start / end overrides
  const [sr, sc] = path[0];
  const [er, ec] = path[path.length - 1];
  cells[sr][sc] = 'start';
  cells[er][ec] = 'end';

  return {
    version: 1,
    title,
    designer,
    theme,
    grid: { rows, cols, cells },
    start: { row: sr, col: sc },
    end: { row: er, col: ec },
    gates: gateDefs,
  };
}

