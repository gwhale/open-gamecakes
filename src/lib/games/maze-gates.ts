// Dead-end branches — cells to carve OUT of the wall so the maze feels
// like a real maze (twists + dead ends + choices) per the designer kid's ticket
// "I want this to be a real maze." Each cell listed below becomes a walkable
// `path` cell; since any adjacent `path` cells are connected, listing the
// right cells creates branches off the main corridor that end in dead ends.
// None of these contain gates — they exist purely for exploration.
const CRAYON_DEAD_ENDS: readonly (readonly [number, number])[] = [
  // Short branch up from the bottom corridor at col 3 → 2 deep
  [12, 3], [11, 3],
  // Branch up from row 10 at col 4 → 2 deep
  [9, 4], [8, 4],
  // Branch down from row 7 col 5 → short
  [8, 5],
  // L-shaped dead end from row 5 → up and left
  [4, 5], [4, 4], [4, 3],
  // Branch down from row 1 col 4 → 1 deep (quick detour)
  [2, 4],
  // Branch off row 11 extending left to make the west side twistier
  [11, 1], [12, 1],
];

function withDeadEnds(
  config: MazeGatesConfig,
  cells: readonly (readonly [number, number])[],
): MazeGatesConfig {
  const nextCells = config.grid.cells.map((row) => [...row]);
  for (const [r, c] of cells) {
    if (nextCells[r]?.[c] === 'wall') {
      nextCells[r][c] = 'path';
    }
  }
  return { ...config, grid: { ...config.grid, cells: nextCells } };
}

export const CRAYON_MAZE: MazeGatesConfig = withDeadEnds(
  buildConfigFromPath({
    rows: 14,
    cols: 10,
    path: CRAYON_PATH,
    gates: CRAYON_GATES,
    title: 'Crayon Maze',
    designer: 'a Gamecakes kid',
    theme: CRAYON_THEME,
  }),
  CRAYON_DEAD_ENDS,
);

// ---------------------------------------------------------------------------
// Tier-scaled generator — same proven (connected) layout as the kid-designed maze,
// but each gate's problem is generated for the kid's tier + chosen operation
// via the shared generateMathChallenge. Problems vary per run.
// ---------------------------------------------------------------------------

/** Gates in this maze are answered on a numeric keypad — the local Challenge
 *  union above has no choice variant — so a concept domain (shapes, time,
 *  comparison) cannot be rendered here. GameLauncher hides those kinds for
 *  maze games via `arithmeticOnly`; this coercion is the belt to that braces,
 *  and it degrades to mixed arithmetic rather than emitting an unanswerable
 *  gate. */
export function generateMazeForTier(tier: number, kind: MathKind = 'mixed'): MazeGatesConfig {
  const mathType: MathType = isConceptType(kind) ? 'mixed' : kind;
  const gates: PathGateSpec[] = CRAYON_GATES.map((g) => {
    const ch = generateMathChallenge(tier, mathType);
    return {
      pathIndex: g.pathIndex,
      challenge: { type: 'numeric', prompt: ch.prompt, answer: ch.answer } as Challenge,
    };
  });
  return withDeadEnds(
    buildConfigFromPath({
      rows: 14,
      cols: 10,
      path: CRAYON_PATH,
      gates,
      title: 'Crayon Maze',
      designer: 'a Gamecakes kid',
      theme: CRAYON_THEME,
    }),
    CRAYON_DEAD_ENDS,
  );
}
